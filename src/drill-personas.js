export function getPersona(key) {
  return DRILL_PERSONAS.find((p) => p.key === key) || null;
}

export function randomPersona(rand = Math.random) {
  return DRILL_PERSONAS[Math.floor(rand() * DRILL_PERSONAS.length)];
}
